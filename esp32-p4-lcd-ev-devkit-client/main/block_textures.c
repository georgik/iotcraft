// Get texture color for a block type at given UV coordinates
uint16_t block_texture_get_pixel(block_type_t type, int u, int v) {
    // Clamp UV to 8x8
    u = u & 7;
    v = v & 7;

    const uint16_t* texture;
    switch (type) {
        case BLOCK_GRASS:
            texture = texture_grass;
            break;
        case BLOCK_DIRT:
            texture = texture_dirt;
            break;
        case BLOCK_STONE:
            texture = texture_stone;
            break;
        case BLOCK_QUARTZ:
            texture = texture_quartz;
            break;
        case BLOCK_GLASS:
            texture = texture_glass;
            break;
        case BLOCK_TERRACOTTA:
            texture = texture_terracotta;
            break;
        case BLOCK_WATER:
            texture = texture_water;
            break;
        default:
            return 0x0000; // Black for unknown
    }

    return texture[v * 8 + u];
}

// Get base color for a block type (fallback)
uint16_t block_type_get_color(block_type_t type) {
    switch (type) {
        case BLOCK_GRASS:     return 0x23c5;
        case BLOCK_DIRT:      return 0x6a44;
        case BLOCK_STONE:     return 0x8c71;
        case BLOCK_QUARTZ:    return 0xffff;
        case BLOCK_GLASS:     return 0x4228;
        case BLOCK_TERRACOTTA: return 0x5bef;
        case BLOCK_WATER:     return 0x5d5b;
        default:              return 0x0000;
    }
}
